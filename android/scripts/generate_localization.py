#!/usr/bin/env python3
"""Generate Android resources and the exact-copy lookup from reviewed translations."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'localization/zh-Hans.json'
JAVA = ROOT / 'app/src/main/java/com/blocknet/wallet/GeneratedTranslations.java'
ENGLISH = ROOT / 'app/src/main/res/values/strings.xml'
CHINESE = ROOT / 'app/src/main/res/values-b+zh+Hans/strings.xml'
FIELD = re.compile(r'%([1-9][0-9]*)\$s')


def resource_name(source):
    words = re.findall(r'[a-z0-9]+', source.lower())[:5]
    stem = '_'.join(words)[:42] or 'text'
    digest = hashlib.sha256(source.encode('utf-8')).hexdigest()[:8]
    return f'loc_{stem}_{digest}'


def xml_text(value):
    return escape(value.replace("'", "\\'").replace('\n', '\\n'))


def generate(catalog):
    if not isinstance(catalog, dict) or not catalog:
        raise ValueError('Localization catalog must be a nonempty object')
    rows = []
    for english, chinese in sorted(catalog.items()):
        if not isinstance(english, str) or not isinstance(chinese, str) or not english or not chinese:
            raise ValueError('Every localization row needs English and Chinese text')
        en_fields = sorted(FIELD.findall(english))
        zh_fields = sorted(FIELD.findall(chinese))
        if en_fields != zh_fields:
            raise ValueError(f'Placeholder mismatch: {english!r}')
        rows.append((resource_name(english), english, chinese, bool(en_fields)))
    if len({row[0] for row in rows}) != len(rows):
        raise ValueError('Resource name collision')

    def resource(chinese):
        lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
        if not chinese:
            lines.append('    <string name="app_name" translatable="false">Blocknet Wallet</string>')
        for name, en, zh, formatted in rows:
            value = zh if chinese else en
            option = '' if formatted else ' formatted="false"'
            lines.append(f'    <string name="{name}"{option}>{xml_text(value)}</string>')
        lines.append('</resources>')
        return '\n'.join(lines) + '\n'

    lines = [
        'package com.blocknet.wallet;', '',
        'import java.util.ArrayList;', 'import java.util.Collections;', 'import java.util.HashMap;',
        'import java.util.List;', 'import java.util.Map;', 'import java.util.regex.Pattern;', '',
        '/** Generated by scripts/generate_localization.py; edit localization/zh-Hans.json. */',
        'final class GeneratedTranslations {',
        '    static final Map<String,Integer> EXACT;',
        '    static final List<Template> TEMPLATES;',
        '    static final class Template {',
        '        final int id; final Pattern pattern;',
        '        Template(int id,String source){',
        '            this.id=id;StringBuilder regex=new StringBuilder("^");',
        '            java.util.regex.Matcher fields=Pattern.compile("%[1-9][0-9]*\\\\$s").matcher(source);',
        '            int start=0;while(fields.find()){regex.append(Pattern.quote(source.substring(start,fields.start()))).append("(.*?)");start=fields.end();}',
        '            regex.append(Pattern.quote(source.substring(start))).append("$");',
        '            pattern=Pattern.compile(regex.toString(),Pattern.DOTALL);',
        '        }',
        '    }',
        '    static {',
        '        Map<String,Integer> exact=new HashMap<>();List<Template> templates=new ArrayList<>();'
    ]
    for name, en, _, formatted in rows:
        string = json.dumps(en, ensure_ascii=False)
        if formatted:
            lines.append(f'        templates.add(new Template(R.string.{name},{string}));')
        else:
            lines.append(f'        exact.put({string},R.string.{name});')
    lines += [
        '        EXACT=Collections.unmodifiableMap(exact);TEMPLATES=Collections.unmodifiableList(templates);',
        '    }',
        '    private GeneratedTranslations(){}',
        '}', ''
    ]
    return {ENGLISH: resource(False), CHINESE: resource(True), JAVA: '\n'.join(lines)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    def unique_pairs(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f'Duplicate localization key: {key!r}')
            result[key] = value
        return result
    catalog = json.loads(CATALOG.read_text(), object_pairs_hook=unique_pairs)
    outputs = generate(catalog)
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f'Localization output is stale: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f'PASS {len(catalog)} bundled localization entries')


if __name__ == '__main__':
    main()
